import sys
from collections import deque

def solve() -> None:
    data = sys.stdin.read().strip().split()
    if not data:
        return
    it = iter(data)
    n = int(next(it))
    m = int(next(it))
    g = [[] for _ in range(n)]
    for _ in range(m):
        u = int(next(it)) - 1
        v = int(next(it)) - 1
        g[u].append(v)
        g[v].append(u)

    color = [-1] * n          # 0/1 partition
    ans = [0] * n
    for start in range(n):
        if color[start] != -1:
            continue
        # BFS this component
        q = deque([start])
        color[start] = 0
        comp = [start]
        ok = True
        while q:
            v = q.popleft()
            for to in g[v]:
                if color[to] == -1:
                    color[to] = color[v] ^ 1
                    q.append(to)
                    comp.append(to)
                elif color[to] == color[v]:
                    print("NO")
                    return
        # decide orientation to get lexicographically smallest
        min_idx = min(comp)
        base = color[min_idx]          # make this side 1
        for v in comp:
            ans[v] = 1 if color[v] == base else 2

    print("YES")
    print(' '.join(map(str, ans)))

if __name__ == "__main__":
    solve()
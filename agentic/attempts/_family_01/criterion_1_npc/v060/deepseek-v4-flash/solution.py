import sys

def solve():
    input_data = sys.stdin.read().strip().split()
    if not input_data:
        return
    it = iter(input_data)
    n = int(next(it))
    m = int(next(it))
    
    adj = [[False] * n for _ in range(n)]
    for _ in range(m):
        u = int(next(it)) - 1
        v = int(next(it)) - 1
        adj[u][v] = adj[v][u] = True
    
    color = [-1] * n
    
    def backtrack(node):
        if node == n:
            return True
        # Try colors 1,2,3
        for c in range(1, 4):
            ok = True
            for nei in range(n):
                if adj[node][nei] and color[nei] == c:
                    ok = False
                    break
            if ok:
                color[node] = c
                if backtrack(node + 1):
                    return True
                color[node] = -1
        return False
    
    if backtrack(0):
        print("YES")
        print(" ".join(str(color[i]) for i in range(n)))
    else:
        print("NO")

if __name__ == "__main__":
    solve()